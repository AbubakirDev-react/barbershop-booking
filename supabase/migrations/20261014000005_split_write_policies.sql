-- Политики записи раздельно по действиям, чтобы SELECT проверялся одной политикой
-- (рекомендация линтера Supabase: multiple_permissive_policies).
drop policy if exists categories_write on public.categories;
drop policy if exists categories_owner_insert on public.categories;
create policy categories_owner_insert on public.categories for insert to authenticated with check ((select public.is_owner()));
drop policy if exists categories_owner_update on public.categories;
create policy categories_owner_update on public.categories for update to authenticated using ((select public.is_owner())) with check ((select public.is_owner()));
drop policy if exists categories_owner_delete on public.categories;
create policy categories_owner_delete on public.categories for delete to authenticated using ((select public.is_owner()));
